#!/usr/bin/env python3
"""Generate the inference-module ablation YAMLs from the shipped online config.

Question 1 (is the agent-level gain SFT or the shared-identity module?) is
answered by holding the SFT checkpoint fixed and swapping only the estimator
behind CrossModalInterpret.  The estimator is picked by

    ONEID_FORCE_MODE  = legacy_hard | candidate_graph | shared_identity
    ONEID_VI_CONFIG   = <one of the YAMLs this script writes>

Both are env-gated in CrossModalInterpret_worker.py, so prompt, tool schema,
decoder settings and checkpoint stay byte-identical across arms.

Arms
----
f_online         shipped online config (reliability.contextual = false) -> the
                 configuration Table 1 of the paper actually ran
f_ctx            contextual reliability switched on with the fitted theta
                 artifact -> the paper's default "F" configuration
f_ctx_nobudget   F minus provenance budgeting                (paper: F-P)
f_ctx_nocap      F minus capacity / null projection         (paper: J+ rung)
f_ctx_nofeedback F with the truth->association term damped to 0 (prior-only A)

Usage
-----
    python scripts/exp/make_arm_configs.py            # write arms/
    python scripts/exp/make_arm_configs.py --list     # just print the plan
"""
from __future__ import annotations

import argparse
import copy
import json
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[1]
BASE = REPO / "tool_server/tool_workers/online_workers/configs/ds_vi/runtime_online.yaml"
OUT_DIR = HERE / "arms"
THETA = "DS_VI/configs/shared_identity/artifacts/contextual_theta_v1.json"

ARMS = {
    "f_online": {
        "_note": "shipped online config; contextual reliability off (this is what Table 1 ran)",
    },
    "f_ctx": {
        "_note": "paper default F: contextual reliability on with the fitted theta artifact",
        "reliability.contextual.enabled": True,
        "reliability.contextual.theta_path": THETA,
    },
    "f_ctx_nobudget": {
        "_note": "F minus provenance budgeting (paper F-P)",
        "reliability.contextual.enabled": True,
        "reliability.contextual.theta_path": THETA,
        "provenance.budget_enabled": False,
        "provenance.group_budget": 1.0,
    },
    "f_ctx_nocap": {
        "_note": "F minus capacity / null projection (paper J+ rung)",
        "reliability.contextual.enabled": True,
        "reliability.contextual.theta_path": THETA,
        "inference.capacity_projection": False,
    },
    "f_ctx_nofeedback": {
        "_note": "F with truth->association feedback damped to 0 (prior-only A)",
        "reliability.contextual.enabled": True,
        "reliability.contextual.theta_path": THETA,
        "inference.feedback_damping": 0.0,
    },
}


def set_dotted(cfg: dict, dotted: str, value) -> None:
    keys = dotted.split(".")
    node = cfg
    for k in keys[:-1]:
        if k not in node or not isinstance(node[k], dict):
            raise KeyError(f"config path not found: {dotted}")
        node = node[k]
    if keys[-1] not in node:
        raise KeyError(f"config leaf not found: {dotted}")
    node[keys[-1]] = value


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--list", action="store_true", help="print the plan, write nothing")
    ap.add_argument("--base", default=str(BASE))
    ap.add_argument("--out", default=str(OUT_DIR))
    args = ap.parse_args()

    base = yaml.safe_load(pathlib.Path(args.base).read_text(encoding="utf-8"))

    out_dir = pathlib.Path(args.out)
    manifest = {}
    for name, raw in ARMS.items():
        overrides = dict(raw)
        note = overrides.pop("_note", "")
        cfg = copy.deepcopy(base)
        for dotted, value in overrides.items():
            set_dotted(cfg, dotted, value)
        header = (
            "# GENERATED by scripts/exp/make_arm_configs.py -- do not hand-edit.\n"
            f"# arm: {name}\n# {note}\n"
            f"# overrides: {json.dumps(overrides, ensure_ascii=False)}\n"
        )
        manifest[name] = {"note": note, "overrides": overrides, "path": str(out_dir / f"{name}.yaml")}
        if args.list:
            print(f"{name:16s} {note}")
            for k, v in overrides.items():
                print(f"                 {k} = {v}")
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        path = out_dir / f"{name}.yaml"
        path.write_text(
            header + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True),
            encoding="utf-8",
        )
        print(f"[ok] {path}")

    if not args.list:
        (out_dir / "manifest.json").write_text(
            json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
        )
        print(f"[ok] {out_dir / 'manifest.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
